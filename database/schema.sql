CREATE TABLE orders (
    order_id            BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number        VARCHAR(40)     NOT NULL,
    customer_id         BIGINT          NOT NULL,
    store_id            INTEGER,
    channel_id          INTEGER         NOT NULL,
    order_date          DATE            NOT NULL,
    order_timestamp     TIMESTAMP       NOT NULL,
    order_status        VARCHAR(30)     NOT NULL DEFAULT 'Completed',
    currency_code       CHAR(3)         NOT NULL DEFAULT 'USD',
    gross_amount        DECIMAL(18, 2)  NOT NULL DEFAULT 0,
    discount_amount     DECIMAL(18, 2)  NOT NULL DEFAULT 0,
    tax_amount          DECIMAL(18, 2)  NOT NULL DEFAULT 0,
    shipping_amount     DECIMAL(18, 2)  NOT NULL DEFAULT 0,
    net_amount          DECIMAL(18, 2)  NOT NULL DEFAULT 0,
    total_amount        DECIMAL(18, 2)  NOT NULL DEFAULT 0,
    employee_id         INTEGER,
    campaign_id         INTEGER,          -- attributable campaign (nullable)
    created_at          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_orders_number UNIQUE (order_number),
    CONSTRAINT ck_orders_currency CHECK (currency_code = 'USD'),
    CONSTRAINT ck_orders_status CHECK (
        order_status IN ('Pending', 'Completed', 'Cancelled', 'Returned', 'PartiallyReturned')
    ),
    CONSTRAINT ck_orders_amounts_nonneg CHECK (
        gross_amount >= 0
        AND discount_amount >= 0
        AND tax_amount >= 0
        AND shipping_amount >= 0
        AND net_amount >= 0
        AND total_amount >= 0
    ),
    CONSTRAINT ck_orders_discount_le_gross CHECK (discount_amount <= gross_amount),
    CONSTRAINT ck_orders_ts_date CHECK (order_timestamp::DATE = order_date),
    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id) REFERENCES customers (customer_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_orders_store
        FOREIGN KEY (store_id) REFERENCES stores (store_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_orders_channel
        FOREIGN KEY (channel_id) REFERENCES channels (channel_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_orders_employee
        FOREIGN KEY (employee_id) REFERENCES employees (employee_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_orders_campaign
        FOREIGN KEY (campaign_id) REFERENCES marketing_campaigns (campaign_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_orders_calendar
        FOREIGN KEY (order_date) REFERENCES calendar_date (full_date)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE order_items (
    order_item_id       BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT          NOT NULL,
    line_number         INTEGER         NOT NULL,
    product_id          BIGINT          NOT NULL,
    quantity            INTEGER         NOT NULL,
    unit_price          DECIMAL(18, 2)  NOT NULL,
    unit_cost           DECIMAL(18, 2)  NOT NULL,
    discount_amount     DECIMAL(18, 2)  NOT NULL DEFAULT 0,
    line_gross_amount   DECIMAL(18, 2)  NOT NULL,
    line_net_amount     DECIMAL(18, 2)  NOT NULL,
    line_cogs_amount    DECIMAL(18, 2)  NOT NULL,
    promotion_id        INTEGER,
    is_gift             BOOLEAN         NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_order_items_line UNIQUE (order_id, line_number),
    CONSTRAINT ck_order_items_line_no CHECK (line_number >= 1),
    CONSTRAINT ck_order_items_qty CHECK (quantity > 0),
    CONSTRAINT ck_order_items_price CHECK (unit_price >= 0),
    CONSTRAINT ck_order_items_cost CHECK (unit_cost >= 0),
    CONSTRAINT ck_order_items_discount CHECK (discount_amount >= 0),
    CONSTRAINT ck_order_items_net CHECK (
        line_net_amount >= 0 AND line_net_amount <= line_gross_amount
    ),
    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id) REFERENCES orders (order_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_order_items_product
        FOREIGN KEY (product_id) REFERENCES products (product_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_order_items_promotion
        FOREIGN KEY (promotion_id) REFERENCES promotions (promotion_id)
        ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE TABLE order_item_promotions (
    order_item_promotion_id BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id           BIGINT      NOT NULL,
    promotion_id            INTEGER     NOT NULL,
    discount_allocated      DECIMAL(18, 2) NOT NULL DEFAULT 0,
    CONSTRAINT uq_order_item_promo UNIQUE (order_item_id, promotion_id),
    CONSTRAINT ck_oip_discount CHECK (discount_allocated >= 0),
    CONSTRAINT fk_oip_item
        FOREIGN KEY (order_item_id) REFERENCES order_items (order_item_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_oip_promo
        FOREIGN KEY (promotion_id) REFERENCES promotions (promotion_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE payments (
    payment_id          BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT          NOT NULL,
    payment_method_id   INTEGER         NOT NULL,
    payment_timestamp   TIMESTAMP       NOT NULL,
    payment_amount      DECIMAL(18, 2)  NOT NULL,
    authorization_code  VARCHAR(50),
    payment_status      VARCHAR(20)     NOT NULL DEFAULT 'Captured',
    created_at          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_payments_amount CHECK (payment_amount > 0),
    CONSTRAINT ck_payments_status CHECK (
        payment_status IN ('Authorized', 'Captured', 'Voided', 'Refunded', 'Failed')
    ),
    CONSTRAINT fk_payments_order
        FOREIGN KEY (order_id) REFERENCES orders (order_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_payments_method
        FOREIGN KEY (payment_method_id) REFERENCES payment_methods (payment_method_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE shipments (
    shipment_id         BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT          NOT NULL,
    dc_id               INTEGER,
    store_id            INTEGER,
    carrier_name        VARCHAR(100),
    tracking_number     VARCHAR(80),
    shipment_status     VARCHAR(30)     NOT NULL DEFAULT 'Shipped',
    ship_date           DATE,
    delivery_date       DATE,
    created_at          TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_shipments_status CHECK (
        shipment_status IN ('Pending', 'Shipped', 'InTransit', 'Delivered', 'Cancelled')
    ),
    CONSTRAINT ck_shipments_dates CHECK (
        delivery_date IS NULL OR ship_date IS NULL OR delivery_date >= ship_date
    ),
    CONSTRAINT ck_shipments_origin CHECK (
        (dc_id IS NOT NULL AND store_id IS NULL)
        OR (dc_id IS NULL AND store_id IS NOT NULL)
        OR (dc_id IS NULL AND store_id IS NULL AND shipment_status IN ('Pending', 'Cancelled'))
    ),
    CONSTRAINT fk_shipments_order
        FOREIGN KEY (order_id) REFERENCES orders (order_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_shipments_dc
        FOREIGN KEY (dc_id) REFERENCES distribution_centers (dc_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_shipments_store
        FOREIGN KEY (store_id) REFERENCES stores (store_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE shipment_items (
    shipment_item_id    BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id         BIGINT          NOT NULL,
    order_item_id       BIGINT          NOT NULL,
    product_id          BIGINT          NOT NULL,
    quantity_shipped    INTEGER         NOT NULL,
