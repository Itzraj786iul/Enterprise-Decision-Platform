CREATE TABLE inventory (
    inventory_id        BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          BIGINT          NOT NULL,
    location_type       VARCHAR(10)     NOT NULL,
    store_id            INTEGER,
    dc_id               INTEGER,
    quantity_on_hand    INTEGER         NOT NULL DEFAULT 0,
    quantity_reserved   INTEGER         NOT NULL DEFAULT 0,
    quantity_available  INTEGER         NOT NULL DEFAULT 0,
    reorder_point       INTEGER,
    max_stock           INTEGER,
    as_of_timestamp     TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_inventory_location_type CHECK (location_type IN ('STORE', 'DC')),
    CONSTRAINT ck_inventory_qty_on_hand CHECK (quantity_on_hand >= 0),
    CONSTRAINT ck_inventory_qty_reserved CHECK (quantity_reserved >= 0),
    CONSTRAINT ck_inventory_qty_available CHECK (quantity_available >= 0),
    CONSTRAINT ck_inventory_reserved_le_onhand CHECK (quantity_reserved <= quantity_on_hand),
    CONSTRAINT ck_inventory_available_calc CHECK (
        quantity_available = quantity_on_hand - quantity_reserved
    ),
    CONSTRAINT ck_inventory_location_xor CHECK (
        (location_type = 'STORE' AND store_id IS NOT NULL AND dc_id IS NULL)
        OR (location_type = 'DC' AND dc_id IS NOT NULL AND store_id IS NULL)
    ),
    CONSTRAINT ck_inventory_reorder CHECK (
        reorder_point IS NULL OR reorder_point >= 0
    ),
    CONSTRAINT ck_inventory_max CHECK (
        max_stock IS NULL OR reorder_point IS NULL OR max_stock >= reorder_point
    ),
    CONSTRAINT uq_inventory_product_location UNIQUE (product_id, location_type, store_id, dc_id),
    CONSTRAINT fk_inventory_product
        FOREIGN KEY (product_id) REFERENCES products (product_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_store
        FOREIGN KEY (store_id) REFERENCES stores (store_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_dc
        FOREIGN KEY (dc_id) REFERENCES distribution_centers (dc_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

